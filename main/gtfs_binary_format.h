#ifndef GTFS_BINARY_FORMAT_H
#define GTFS_BINARY_FORMAT_H

// Wire format: little-endian, packed bytes (never sizeof a C struct).
// Source: scripts/build_gtfs_bundle.py struct.Struct declarations.
// PRIMARY header <8sIIqqqI, record <32sqIHH.
// UPSTREAM header <8sII, record <32sH14sii; version is in its magic.
// BUNDLE header <8sIIIqqq32sI, followed by primary then upstream.
// Primary/upstream checksums: FNV-1a over record bytes.
// Bundle SHA-256 covers both payloads; CRC32 covers header bytes [0,76).
// String fields are fixed byte arrays, padded with NUL by the generator.
#define GTFS_PRIMARY_VERSION_OFFSET 8
#define GTFS_PRIMARY_COUNT_OFFSET 12
#define GTFS_PRIMARY_VALID_FROM_OFFSET 24
#define GTFS_PRIMARY_VALID_UNTIL_OFFSET 32
#define GTFS_PRIMARY_CHECKSUM_OFFSET 40
#define GTFS_UPSTREAM_COUNT_OFFSET 8
#define GTFS_UPSTREAM_CHECKSUM_OFFSET 12
#define GTFS_BUNDLE_VERSION_OFFSET 8
#define GTFS_BUNDLE_PRIMARY_LENGTH_OFFSET 12
#define GTFS_BUNDLE_UPSTREAM_LENGTH_OFFSET 16
#define GTFS_BUNDLE_GENERATED_OFFSET 20
#define GTFS_BUNDLE_VALID_FROM_OFFSET 28
#define GTFS_BUNDLE_VALID_UNTIL_OFFSET 36
#define GTFS_BUNDLE_SHA256_OFFSET 44
#define GTFS_BUNDLE_CRC32_OFFSET 76
#define GTFS_PRIMARY_RECORD_ARRIVAL_OFFSET 32
#define GTFS_PRIMARY_RECORD_SERVICE_DATE_OFFSET 40
#define GTFS_PRIMARY_RECORD_SEQUENCE_OFFSET 44
#define GTFS_PRIMARY_RECORD_LINE_OFFSET 46
#define GTFS_UPSTREAM_RECORD_SEQUENCE_OFFSET 32
#define GTFS_UPSTREAM_RECORD_STOP_ID_OFFSET 34
#define GTFS_UPSTREAM_RECORD_ARRIVAL_OFFSET 48
#define GTFS_UPSTREAM_RECORD_DEPARTURE_OFFSET 52
#define GTFS_PRIMARY_MAGIC "POZGTFS1"
#define GTFS_MAGIC_BYTES 8
#define GTFS_UPSTREAM_MAGIC "POZUPV01"
#define GTFS_BUNDLE_MAGIC "POZBND01"
#define GTFS_TRIP_ID_BYTES 32
#define GTFS_STOP_ID_BYTES 14
#define GTFS_SHA256_BYTES 32
#define GTFS_FORMAT_VERSION 1
#define GTFS_PRIMARY_HEADER_BYTES 44U
#define GTFS_PRIMARY_RECORD_BYTES 48U
#define GTFS_UPSTREAM_HEADER_BYTES 16U
#define GTFS_UPSTREAM_RECORD_BYTES 56U
#define GTFS_BUNDLE_HEADER_BYTES (80U)

#endif
